@pytest.mark.parametrize("case", SYNTHETIC_CASES, ids=lambda case: case["name"])
def test_ten_analytically_solved_euclidean_counterexamples(case):
    args = inputs_for_case(case)
    result = select_target(*args)
    near, far = result["candidates"]
    expected = case["expected"]
    assert [near["path_distance_cm"], near["turn_deg"], near["cost_cm"],
            far["path_distance_cm"], far["turn_deg"], far["cost_cm"]] == pytest.approx(expected)
    assert near["euclidean_cm"] == pytest.approx(100)
    assert far["euclidean_cm"] == pytest.approx(200)
    assert result["selected_candidate_id"] == "far"
    assert result["selected_cost_cm"] <= .9 * near["cost_cm"]
    assert sum(leg["distance_cm"] for leg in far["path"]) == pytest.approx(expected[3])
    assert near["projection"]["progress_cm"] == pytest.approx(case.get("near_s", 10))
    assert far["projection"]["progress_cm"] == pytest.approx(case.get("far_s", 20))


def single_road(one_way=False):
    return ([{"obj_id": "t", "x": 0, "z": .7}],
            {"edges": [edge("road", "A", "B", 100, one_way)]},
            {"roadId": "road", "roadProgressCm": 20, "onRoad": True},
            {"rightCm": 0, "forwardCm": 20, "headingDeg": 0},
            {"roads": {"road": [{"s": 0, "x": 0, "z": 0}, {"s": 100, "x": 0, "z": 1}]},
             "intervals": {"road": [[0, 100]]}}, .5)


def test_same_road_uses_partial_distance_not_node_detour():
    result = select_target(*single_road())
    assert result["selected_path_distance_cm"] == pytest.approx(50)
    assert result["candidates"][0]["path"][0]["kind"] == "same_road_partial"


def test_oneway_behind_target_unreachable_then_return_loop():
    args = list(single_road(True)); args[0][0]["z"] = .1
    result = select_target(*args)
    assert result["selected_candidate_id"] is None
    assert result["candidates"][0]["status"] == "unreachable"
    args[1]["edges"].append(edge("return", "B", "A", 150, True))
    result = select_target(*args)
    assert result["selected_path_distance_cm"] == pytest.approx(80 + 150 + 10)


