def edge(name, a, b, length, one_way=False):
    return {"roadId": name, "fromNodeId": a, "toNodeId": b,
            "lengthCm": length, "oneWay": one_way}


def inputs_for_case(case):
    """Public-only fixture. Local observed road spans need not reveal transit roads."""
    s = case.get("current_s", 40)
    nprogress, fprogress = case.get("near_s", 10), case.get("far_s", 20)
    near, far = case.get("near_xy", (0, 1)), case.get("far_xy", (2, 0))
    geometry = {"roads": {"current": [{"s": 0, "x": 0, "z": -s / 100},
                                      {"s": 40, "x": 0, "z": (40 - s) / 100}]},
                "intervals": {"current": [[0, 40]]}}
    # Each target lies at the centre of an observed ten-centimetre span.
    for name, progress, point in [("near", nprogress, near), ("far", fprogress, far)]:
        geometry["roads"][name] = [{"s": progress - 5, "x": point[0] - .05, "z": point[1]},
                                    {"s": progress + 5, "x": point[0] + .05, "z": point[1]}]
        geometry["intervals"][name] = [[progress - 5, progress + 5]]
    return ([{"obj_id": "near", "x": near[0], "z": near[1], "confidence": .99},
             {"obj_id": "far", "x": far[0], "z": far[1], "confidence": .6}],
            {"edges": [edge("current", "S", "O", 40, case.get("current_one_way", False)),
                       edge("near", "N0", "N1", 100, case.get("near_one_way", False)),
                       edge("far", "F0", "F1", 100), *case["links"]]},
            {"roadId": "current", "roadProgressCm": s, "onRoad": True},
            {"rightCm": 0, "forwardCm": 0, "headingDeg": case.get("heading", 0), "tick": 0},
            geometry, case.get("k", .5))


